1. CREATE TABLE

CREATE TABLE TEST_EXECUTION (
    TEST_CASE_ID VARCHAR2(20),
    MODULE VARCHAR2(30),
    TEST_STATUS VARCHAR2(20),
    PRIORITY VARCHAR2(10)
);


