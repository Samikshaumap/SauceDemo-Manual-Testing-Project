3. SAVE CHANGES

COMMIT;


4. DISPLAY ALL TEST EXECUTION RECORDS

SELECT *
FROM TEST_EXECUTION;


5. FILTER LOGIN MODULE RECORDS

SELECT * 
FROM TEST_EXECUTION
WHERE MODULE = 'Login';


6. DISPLAY ONLY PASSED TEST CASES

SELECT * 
FROM TEST_EXECUTION
WHERE TEST_STATUS = 'PASS';


7. DISPLAY HIGH PRIORITY TEST CASES

SELECT * 
FROM TEST_EXECUTION
WHERE PRIORITY = 'High';


8. SORT RECORDS BY MODULE (ASCENDING ORDER)

SELECT * 
FROM TEST_EXECUTION
ORDER BY MODULE ASC;


9. SORT RECORDS BY PRIORITY

SELECT * 
FROM TEST_EXECUTION
ORDER BY PRIORITY ASC;


10. COUNT TEST CASES MODULE-WISE

SELECT MODULE, COUNT(*)
FROM TEST_EXECUTION
GROUP BY MODULE;


11. COUNT TEST CASES STATUS-WISE

SELECT TEST_STATUS, COUNT(*)
FROM TEST_EXECUTION
GROUP BY TEST_STATUS;


12. COUNT TOTAL TEST EXECUTION RECORDS

SELECT COUNT(*)
FROM TEST_EXECUTION;
